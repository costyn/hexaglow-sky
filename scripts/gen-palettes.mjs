// Generates src/wledPalettes.ts from WLED's wled00/palettes.cpp (v0.16).
// Usage: node scripts/gen-palettes.mjs  (expects scripts/wled-palettes.cpp)
import fs from 'node:fs';
const src = fs.readFileSync(new URL('./wled-palettes.cpp', import.meta.url), 'utf8');
const NAMES = ["Default","* Random Cycle","* Color 1","* Colors 1&2","* Color Gradient","* Colors Only","Party","Cloud","Lava","Ocean",
"Forest","Rainbow","Rainbow Bands","Sunset","Rivendell","Breeze","Red & Blue","Yellowout","Analogous","Splash",
"Pastel","Sunset 2","Beach","Vintage","Departure","Landscape","Beech","Sherbet","Hult","Hult 64",
"Drywet","Jul","Grintage","Rewhi","Tertiary","Fire","Icefire","Cyane","Light Pink","Autumn",
"Magenta","Magred","Yelmag","Yelblu","Orange & Teal","Tiamat","April Night","Orangery","C9","Sakura",
"Aurora","Atlantica","C9 2","C9 New","Temperature","Aurora 2","Retro Clown","Candy","Toxy Reaf","Fairy Reaf",
"Semi Blue","Pink Candy","Red Reaf","Aqua Flash","Yelblu Hot","Lite Light","Red Flash","Blink Red","Red Shift","Red Tide",
"Candy2","Traffic Light","Fireworks"];
const CSS = { Blue:0x0000FF, DarkBlue:0x00008B, SkyBlue:0x87CEEB, LightBlue:0xADD8E6, White:0xFFFFFF, Black:0, Maroon:0x800000,
  DarkRed:0x8B0000, Red:0xFF0000, Orange:0xFFA500, MidnightBlue:0x191970, Navy:0x000080, MediumBlue:0x0000CD, SeaGreen:0x2E8B57,
  Teal:0x008080, CadetBlue:0x5F9EA0, DarkCyan:0x008B8B, CornflowerBlue:0x6495ED, Aquamarine:0x7FFFD4, Aqua:0x00FFFF,
  LightSkyBlue:0x87CEFA, DarkGreen:0x006400, DarkOliveGreen:0x556B2F, Green:0x008000, ForestGreen:0x228B22, OliveDrab:0x6B8E23,
  MediumAquamarine:0x66CDAA, LimeGreen:0x32CD32, YellowGreen:0x9ACD32, LightGreen:0x90EE90, LawnGreen:0x7CFC00 };
const blocks = {};
for (const m of src.matchAll(/(\w+)\[\]\s*PROGMEM\s*=\s*\{([\s\S]*?)\};/g)) blocks[m[1]] = m[2];
for (const m of src.matchAll(/TProgmemRGBPalette16\s+(\w+)\s+PROGMEM\s*=\s*\{([\s\S]*?)\};/g)) blocks[m[1]] = m[2];
const listOf = (name) => { const m = src.match(new RegExp(name + '\\[\\]\\s*PROGMEM\\s*=\\s*\\{([\\s\\S]*?)\\};')); return [...m[1].matchAll(/&?(\w+)\s*,?\s*\/\/(\d+)-/g)].map(x => [x[1], +x[2]]); };
const out = {};
const hex = (n) => [(n >> 16) & 255, (n >> 8) & 255, n & 255];
for (const [name, id] of listOf('fastledPalettes')) {
  const body = blocks[name].replace(/\/\/.*$/gm, '');
  const cols = [...body.matchAll(/CRGB::(\w+)|0x([0-9A-Fa-f]{6})/g)].map(m => m[1] ? hex(CSS[m[1]] ?? (() => { throw new Error(m[1]); })()) : hex(parseInt(m[2], 16)));
  if (cols.length !== 16) throw new Error(name + ' ' + cols.length);
  out[id] = { name: NAMES[id], type: 'fl16', stops: cols.map((c, i) => [i * 16, ...c]) };
}
for (const [name, id] of listOf('gGradientPalettes')) {
  const nums = blocks[name].replace(/\/\/.*$/gm, '').match(/\d+/g).map(Number);
  const stops = []; for (let i = 0; i < nums.length; i += 4) stops.push(nums.slice(i, i + 4));
  out[id] = { name: NAMES[id], type: 'grad', stops };
}
let ts = '// AUTO-GENERATED by scripts/gen-palettes.mjs from WLED wled00/palettes.cpp — do not edit.\n';
ts += 'export type PaletteDef = { name: string; type: "fl16" | "grad"; stops: number[][] };\n';
ts += 'export const WLED_PALETTE_NAMES: string[] = ' + JSON.stringify(NAMES) + ';\n';
ts += 'export const WLED_PALETTES: Record<number, PaletteDef> = {\n';
for (const id of Object.keys(out).sort((a, b) => a - b)) ts += `  ${id}: ${JSON.stringify(out[id])},\n`;
ts += '};\n';
fs.writeFileSync(new URL('../src/wledPalettes.ts', import.meta.url), ts);
console.log('palettes:', Object.keys(out).length);
